        + ",".join(map(str, ticks))
        + "},"
        + r"axis x line*=bottom,axis y line*=left,axis line style={black!40},tick style={black!40},"
        + r"tick label style={font=\fontsize{8}{9}\selectfont},label style={font=\fontsize{8}{9}\selectfont},"
        + r"enlargelimits=false,clip=true]"
        + "\n"
        + "".join(axes)
        + r"\end{groupplot}\end{tikzpicture}"
