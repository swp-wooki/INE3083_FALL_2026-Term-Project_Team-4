def tex_name(model):
    return NAMES[model].replace("–", "--").replace("&", r"\&")


def plot_style(model):
    width = 1.65 if model == "SP500" else 1.05
    return f"color=series{SERIES.index(model)},line width={width}pt,{TEX_DASH[model]}"


def definitions():
    return (
        "\n".join(
            r"\definecolor{series" + str(i) + "}{HTML}{" + COLORS[m][1:] + "}"
            for i, m in enumerate(SERIES)
        )
        + "\n"
    )


def coords(x, y):
    return " ".join(f"({a:g},{b:.8f})" for a, b in zip(x, y))


def legend_tex():
    entries = [
        r"\tikz[baseline=-0.5ex]{\draw["
        + plot_style(m)
        + r"] (0,0)--(0.47,0);}"
        + r"\ "
        + (r"\textbf{" + tex_name(m) + "}" if m == "SP500" else tex_name(m))
        for m in SERIES
    ]
    return (
        r"{\fontsize{8}{9}\selectfont "
        + r"\quad ".join(entries[:3])
        + r"\par\smallskip "
        + r"\quad ".join(entries[3:])
        + "}\n"
    )


